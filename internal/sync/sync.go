// Package sync keeps the configuration directory in a git repository so it
// can travel between machines.
//
// Only config.yaml is tracked. init.zsh is generated and would conflict on
// every machine; local.yaml exists precisely to hold what must not travel.
// Credentials are never involved: they live in the OS keychain, which is
// deliberately not exportable, so a synced config carries names and nothing
// else.
package sync

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

// gitignore is written into the config repo. Everything not listed is either
// generated or machine-specific.
const gitignore = `# Generated by loadout on each apply; never worth syncing.
init.*
# Machine-specific overrides. This file is the reason sync is safe:
# whatever differs per machine goes here and stays here.
local.yaml
`

// Repo is a git repository holding the configuration directory.
type Repo struct {
	Dir string
}

// New points at a configuration directory.
func New(dir string) *Repo { return &Repo{Dir: dir} }

// git runs a git command in the repo and returns trimmed stdout.
func (r *Repo) git(args ...string) (string, error) {
	cmd := exec.Command("git", args...)
	cmd.Dir = r.Dir
	var out, errb bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &errb
	if err := cmd.Run(); err != nil {
		msg := strings.TrimSpace(errb.String())
		if msg == "" {
			msg = err.Error()
		}
		return "", fmt.Errorf("git %s: %s", strings.Join(args, " "), msg)
	}
	return strings.TrimSpace(out.String()), nil
}

// Initialised reports whether the directory is already a git repo.
func (r *Repo) Initialised() bool {
	_, err := os.Stat(filepath.Join(r.Dir, ".git"))
	return err == nil
}

// Init turns the config directory into a git repository. remote may be empty,
// in which case the repo is local until one is added.
func (r *Repo) Init(remote string) error {
	if _, err := exec.LookPath("git"); err != nil {
		return errors.New("git is not installed")
	}
	if r.Initialised() {
		return fmt.Errorf("%s is already a git repository", r.Dir)
	}
	if err := os.MkdirAll(r.Dir, 0o755); err != nil {
		return err
	}
	if _, err := r.git("init", "-b", "main"); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(r.Dir, ".gitignore"), []byte(gitignore), 0o644); err != nil {
		return err
	}
	if remote != "" {
		if _, err := r.git("remote", "add", "origin", remote); err != nil {
			return err
		}
	}
	return nil
}

// Remote returns the configured origin, or "" if there is none.
func (r *Repo) Remote() string {
	out, err := r.git("remote", "get-url", "origin")
	if err != nil {
		return ""
	}
	return out
}

// SetRemote adds or replaces origin.
func (r *Repo) SetRemote(url string) error {
	if r.Remote() == "" {
		_, err := r.git("remote", "add", "origin", url)
		return err
	}
	_, err := r.git("remote", "set-url", "origin", url)
	return err
}

// Status describes the repo's state.
type Status struct {
	Dirty   bool
	Changes []string
	Branch  string
	Remote  string
	Ahead   int
	Behind  int
}

// Status inspects the repo.
func (r *Repo) Status() (*Status, error) {
	if !r.Initialised() {
		return nil, fmt.Errorf("%s is not a git repository: run 'loadout sync init'", r.Dir)
	}
	s := &Status{Remote: r.Remote()}

	if out, err := r.git("status", "--porcelain"); err == nil && out != "" {
		s.Dirty = true
		s.Changes = strings.Split(out, "\n")
	}
	// rev-parse fails on an unborn branch, i.e. before the first commit.
	// branch --show-current reports the name regardless.
	if out, err := r.git("branch", "--show-current"); err == nil && out != "" {
		s.Branch = out
	}

	// Ahead/behind only means something once an upstream exists.
	if out, err := r.git("rev-list", "--left-right", "--count", "@{upstream}...HEAD"); err == nil {
		var behind, ahead int
		if _, scanErr := fmt.Sscanf(out, "%d\t%d", &behind, &ahead); scanErr == nil {
			s.Behind, s.Ahead = behind, ahead
		}
	}
	return s, nil
}

// TrackedFiles lists what is under version control, so a user can see exactly
// what would leave the machine.
func (r *Repo) TrackedFiles() ([]string, error) {
	out, err := r.git("ls-files")
	if err != nil {
		return nil, err
	}
	if out == "" {
		return nil, nil
	}
	return strings.Split(out, "\n"), nil
}

// ErrSecrets is returned when a push is blocked by the scanner.
type ErrSecrets struct {
	File     string
	Findings []Finding
}

func (e *ErrSecrets) Error() string {
	var b strings.Builder
	fmt.Fprintf(&b, "refusing to push: %s looks like it contains a live credential\n", e.File)
	for _, f := range e.Findings {
		fmt.Fprintf(&b, "  %s\n", f)
	}
	b.WriteString("\nSecrets belong in the keychain, not in config. Use 'loadout cred set',\n")
	b.WriteString("and reference them as \"cred:<name>\" where a value is needed.")
	return b.String()
}

// scanTracked checks every tracked text file for credential-shaped content.
func (r *Repo) scanTracked() error {
	files, err := r.TrackedFiles()
	if err != nil {
		return err
	}
	// A file staged for the first time is not yet tracked, so include those.
	if staged, err := r.git("diff", "--cached", "--name-only"); err == nil && staged != "" {
		files = append(files, strings.Split(staged, "\n")...)
	}

	seen := map[string]bool{}
	for _, f := range files {
		if f == "" || seen[f] {
			continue
		}
		seen[f] = true
		data, err := os.ReadFile(filepath.Join(r.Dir, f))
		if err != nil {
			continue
		}
		if findings := Scan(string(data)); len(findings) > 0 {
			return &ErrSecrets{File: f, Findings: findings}
		}
	}
	return nil
}

// Push stages everything, scans it, commits and pushes.
//
// The scan runs before the commit rather than before the push, so a secret
// never enters the history at all. Once committed, removing it needs a
// rewrite.
func (r *Repo) Push(message string) (pushed bool, err error) {
	if !r.Initialised() {
		return false, fmt.Errorf("%s is not a git repository: run 'loadout sync init'", r.Dir)
	}
	if _, err := r.git("add", "-A"); err != nil {
		return false, err
	}
	if err := r.scanTracked(); err != nil {
		// Unstage so the working tree is left as it was found.
		_, _ = r.git("reset")
		return false, err
	}

	staged, err := r.git("diff", "--cached", "--name-only")
	if err != nil {
		return false, err
	}
	if staged != "" {
		if message == "" {
			message = "Update loadout configuration"
		}
		if _, err := r.git("commit", "-m", message); err != nil {
			return false, err
		}
	}

	if r.Remote() == "" {
		return false, errors.New("no remote configured: run 'loadout sync remote <url>'")
	}

	branch, _ := r.git("branch", "--show-current")
	if branch == "" {
		branch = "main"
	}
	if _, err := r.git("push", "-u", "origin", branch); err != nil {
		return false, err
	}
	return true, nil
}

// Pull fetches and merges from the remote.
func (r *Repo) Pull() (string, error) {
	if !r.Initialised() {
		return "", fmt.Errorf("%s is not a git repository: run 'loadout sync init'", r.Dir)
	}
	if r.Remote() == "" {
		return "", errors.New("no remote configured: run 'loadout sync remote <url>'")
	}
	// Refuse to merge over uncommitted edits rather than risk losing them.
	if out, err := r.git("status", "--porcelain"); err == nil && out != "" {
		return "", errors.New("you have uncommitted changes: run 'loadout sync push' first")
	}
	branch, _ := r.git("branch", "--show-current")
	if branch == "" {
		branch = "main"
	}
	return r.git("pull", "--ff-only", "origin", branch)
}
