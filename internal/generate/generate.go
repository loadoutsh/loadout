// Package generate renders the catalog and the user's config into a single
// shell file that gets sourced at shell start.
package generate

import (
	"bytes"
	"fmt"
	"path/filepath"
	"sort"
	"strings"
	"text/template"

	"github.com/wesscoby/loadout/internal/catalog"
	"github.com/wesscoby/loadout/internal/config"
	"github.com/wesscoby/loadout/internal/generate/backend"
)

// Options controls a render.
type Options struct {
	Shell  string // dialect name, e.g. "zsh"
	GOOS   string // target platform, e.g. "linux"
	BinDir string // managed bin directory to put on PATH
}

// Generator renders shell from a catalog and a config.
type Generator struct {
	cat *catalog.Catalog
	cfg *config.Config
	be  backend.Backend
	opt Options
}

// New builds a Generator.
func New(cat *catalog.Catalog, cfg *config.Config, opt Options) (*Generator, error) {
	be, err := backend.Get(opt.Shell)
	if err != nil {
		return nil, err
	}
	return &Generator{cat: cat, cfg: cfg, be: be, opt: opt}, nil
}

// tmplData is what function templates are rendered against. It flattens the
// config and adds a few derived conveniences so templates stay free of logic.
type tmplData struct {
	*config.Config
	Editor          string
	DefaultIdentity string
	IdentityIDs     string
	HostAliases     string
}

func (g *Generator) templateData() tmplData {
	d := tmplData{Config: g.cfg, Editor: "code"}

	if len(g.cfg.Editors) > 0 {
		d.Editor = g.cfg.Editors[0].Command
	}

	ids := make([]string, 0, len(g.cfg.Identities))
	for _, id := range g.cfg.Identities {
		ids = append(ids, id.ID)
		if id.Default {
			d.DefaultIdentity = id.ID
		}
	}
	// Fall back to the first identity so `s` with no argument still works.
	if d.DefaultIdentity == "" && len(ids) > 0 {
		d.DefaultIdentity = ids[0]
	}
	d.IdentityIDs = strings.Join(ids, ", ")

	hosts := make([]string, 0, len(g.cfg.Hosts))
	for _, h := range g.cfg.Hosts {
		hosts = append(hosts, h.Alias)
	}
	d.HostAliases = strings.Join(hosts, ", ")

	return d
}

// funcMap is available inside function templates.
var funcMap = template.FuncMap{
	// shpath rewrites a leading ~ into $HOME. A tilde does not expand inside
	// double quotes, so a path interpolated into a quoted test would silently
	// fail; $HOME works in both quoted and unquoted position.
	"shpath": func(p string) string {
		if p == "~" {
			return "$HOME"
		}
		if strings.HasPrefix(p, "~/") {
			return "$HOME/" + p[2:]
		}
		return p
	},
}

// Render produces the complete shell file.
func (g *Generator) Render() ([]byte, error) {
	var b bytes.Buffer

	g.writeHeader(&b)

	if err := g.writeAliases(&b); err != nil {
		return nil, err
	}
	if err := g.writeConfigAliases(&b); err != nil {
		return nil, err
	}
	if err := g.writeFunctions(&b); err != nil {
		return nil, err
	}
	g.writePath(&b)

	return b.Bytes(), nil
}

func (g *Generator) writeHeader(b *bytes.Buffer) {
	fmt.Fprintln(b, g.be.Comment("Generated by loadout. Do not edit."))
	fmt.Fprintln(b, g.be.Comment("Edit ~/.config/loadout/config.yaml, then run 'loadout apply'."))
	fmt.Fprintln(b, g.be.Comment(fmt.Sprintf("shell=%s platform=%s", g.opt.Shell, g.opt.GOOS)))
	fmt.Fprintln(b)
}

// enabledPacks is the set of packs the user has switched on.
func (g *Generator) enabledPacks() map[string]bool {
	on := map[string]bool{}
	for _, p := range g.cfg.Packs {
		on[p] = true
	}
	return on
}

func (g *Generator) disabledAliases() map[string]bool {
	off := map[string]bool{}
	for _, n := range g.cfg.Aliases.Disabled {
		off[n] = true
	}
	return off
}

// writeAliases emits the shipped catalog, grouped by category.
func (g *Generator) writeAliases(b *bytes.Buffer) error {
	packs := g.enabledPacks()
	disabled := g.disabledAliases()

	byCategory := map[string][]catalog.Alias{}
	var order []string
	for _, a := range g.cat.Aliases {
		if disabled[a.Name] {
			continue
		}
		if a.Pack != "" && !packs[a.Pack] {
			continue
		}
		if _, ok := a.Resolve(g.opt.GOOS); !ok {
			continue
		}
		if _, seen := byCategory[a.Category]; !seen {
			order = append(order, a.Category)
		}
		byCategory[a.Category] = append(byCategory[a.Category], a)
	}

	for _, cat := range order {
		fmt.Fprintln(b, g.be.SectionHeader(strings.ToUpper(cat[:1])+cat[1:]))
		for _, a := range byCategory[cat] {
			cmd, _ := a.Resolve(g.opt.GOOS)
			line := g.be.Alias(a.Name, cmd)
			if a.Comment != "" {
				line += " " + g.be.Comment(a.Comment)
			}
			fmt.Fprintln(b, line)
		}
		fmt.Fprintln(b)
	}
	return nil
}

// writeConfigAliases emits the aliases that come from user config rather than
// from the catalog: hosts, workspaces, node versions, git branches, editors.
func (g *Generator) writeConfigAliases(b *bytes.Buffer) error {
	var lines []string
	add := func(name, cmd string) { lines = append(lines, g.be.Alias(name, cmd)) }

	// Git branch shortcuts
	main, dev := g.cfg.Git.MainBranch, g.cfg.Git.DevBranch
	add("gcop", fmt.Sprintf("git checkout %s && git pull origin %s", main, main))
	add("gcod", fmt.Sprintf("git checkout %s && git pull origin %s", dev, dev))
	add("dpush", fmt.Sprintf("git push origin %s", dev))
	add("dpull", fmt.Sprintf("git pull origin %s", dev))

	// Node versions
	for _, v := range g.cfg.NodeVersions {
		add(v, "nvm use "+v)
	}

	// Editors beyond the default get an alias each, plus a `<name>.` variant
	// for the current directory.
	for i, e := range g.cfg.Editors {
		if i == 0 {
			continue
		}
		add(e.Name, e.Command)
		add(e.Name+".", e.Command+" .")
	}

	// Host shortcuts
	for _, h := range g.cfg.Hosts {
		if h.Shortcut {
			add(h.Alias, "ssh "+h.Alias)
		}
	}

	// Workspaces paired with a tmux session
	for _, w := range g.cfg.Workspaces {
		if w.TmuxSession != "" {
			add(w.Name, fmt.Sprintf("pw %s && ta %s", w.Name, w.TmuxSession))
		}
	}

	// Managed binaries that want a shorter name
	for _, bin := range g.cfg.Binaries {
		if bin.Name == "duckdb" {
			add("ddb", "duckdb")
		}
	}

	// User's own aliases
	for _, c := range g.cfg.Aliases.Custom {
		if len(c.Platform) > 0 {
			match := false
			for _, p := range c.Platform {
				if p == g.opt.GOOS {
					match = true
				}
			}
			if !match {
				continue
			}
		}
		add(c.Name, c.Command)
	}

	if len(lines) == 0 {
		return nil
	}
	fmt.Fprintln(b, g.be.SectionHeader("From your config"))
	for _, l := range lines {
		fmt.Fprintln(b, l)
	}
	fmt.Fprintln(b)
	return nil
}

// writeFunctions renders each function template against the config.
func (g *Generator) writeFunctions(b *bytes.Buffer) error {
	data := g.templateData()

	fns := make([]catalog.Function, len(g.cat.Functions))
	copy(fns, g.cat.Functions)
	sort.Slice(fns, func(i, j int) bool { return fns[i].Name < fns[j].Name })

	fmt.Fprintln(b, g.be.SectionHeader("Functions"))
	for _, fn := range fns {
		t, err := template.New(fn.Name).Funcs(funcMap).Parse(fn.Template)
		if err != nil {
			return fmt.Errorf("function %s: %w", fn.Name, err)
		}
		var out bytes.Buffer
		if err := t.Execute(&out, data); err != nil {
			return fmt.Errorf("function %s: %w", fn.Name, err)
		}
		rendered := strings.TrimSpace(out.String())
		// A template driven entirely by config renders empty when that config
		// is absent; emitting nothing is correct.
		if rendered == "" {
			continue
		}
		fmt.Fprintln(b, rendered)
		fmt.Fprintln(b)
	}
	return nil
}

func (g *Generator) writePath(b *bytes.Buffer) {
	if g.opt.BinDir == "" {
		return
	}
	fmt.Fprintln(b, g.be.SectionHeader("Managed binaries"))
	fmt.Fprintln(b, g.be.Comment("Appended, not prepended, so a managed binary cannot shadow a system one."))
	fmt.Fprintln(b, g.be.PathAppend(g.opt.BinDir))
	fmt.Fprintln(b)
}

// OutputPath is where the generated file belongs.
func OutputPath(shell string) (string, error) {
	dir, err := config.Dir()
	if err != nil {
		return "", err
	}
	be, err := backend.Get(shell)
	if err != nil {
		return "", err
	}
	return filepath.Join(dir, "init."+be.Ext()), nil
}
